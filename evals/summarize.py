"""Aggregates results into a Markdown summary with confidence intervals and cost.

    python -m evals.summarize

Every number is recomputed from the rows in results.jsonl and errors.jsonl. A
score is the mean over cases of each case's mean over its repetitions, counting
only the cases where the metric is defined. Intervals are 95% bootstrap
intervals over cases, with a fixed seed so the output is reproducible.
"""

import argparse
import json
import random
import statistics
from pathlib import Path

from evals import DEFAULT_FLOW, VARIANT
from evals.judge import served_as

RESAMPLES = 2000
CACHE_READ_RATE = 0.1  # cached input is billed at this fraction of the input price
CACHE_WRITE_RATE = 1.25


def _read_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError:
            continue  # a torn line from an interrupted run
    return rows


def variants(flow: Path) -> list[str]:
    names = [p.name for p in flow.iterdir() if p.is_dir() and VARIANT.match(p.name)]
    return sorted(names, key=lambda n: -1 if n == "baseline" else int(n[1:]))


def case_means(rows: list[dict], value) -> dict[str, float]:
    """Mean per case over its scored repetitions, skipping reps where value() is None."""
    by_case: dict[str, list[float]] = {}
    for row in rows:
        if row.get("status", "ok") != "ok":
            continue
        v = value(row)
        if v is not None:
            by_case.setdefault(row["prompt_id"], []).append(v)
    return {case: statistics.fmean(values) for case, values in by_case.items()}


def bootstrap_ci(values: list[float], seed: int = 0) -> tuple[float, float] | None:
    """95% percentile bootstrap interval for the mean. None if there are too few values."""
    if len(values) < 2:
        return None
    rng = random.Random(seed)
    means = sorted(
        statistics.fmean(rng.choices(values, k=len(values))) for _ in range(RESAMPLES)
    )
    return means[int(0.025 * RESAMPLES)], means[int(0.975 * RESAMPLES) - 1]


def price_for(model: str, prices: dict) -> dict | None:
    return next((p for name, p in prices.items() if served_as(name, model)), None)


def cost_usd(usage: dict, price: dict | None) -> float | None:
    """Dollars for one usage record, or None when the model has no listed price."""
    if price is None:
        return None
    input_equivalent = (
        usage.get("input_tokens", 0)
        + CACHE_READ_RATE * usage.get("cache_read_input_tokens", 0)
        + CACHE_WRITE_RATE * usage.get("cache_creation_input_tokens", 0)
    )
    return (input_equivalent * price["in"] + usage.get("output_tokens", 0) * price["out"]) / 1e6


def app_cost(row: dict, prices: dict) -> float | None:
    costs = [cost_usd(u, price_for(m, prices)) for m, u in row.get("usage_by_model", {}).items()]
    return None if None in costs else sum(costs)


def judge_cost(row: dict, prices: dict) -> float | None:
    usage = row.get("judge_usage") or {}
    if not any(usage.values()):
        return 0.0
    return cost_usd(usage, price_for(row.get("judge_model", ""), prices))


def _score(values: list[float]) -> str:
    if not values:
        return "n/a"
    ci = bootstrap_ci(values)
    interval = f" [{ci[0]:.2f}, {ci[1]:.2f}]" if ci else ""
    return f"{statistics.fmean(values):.2f}{interval} (n={len(values)})"


def _money(values: list[float | None]) -> str:
    if not values or None in values:
        return "not measured"
    return f"${statistics.fmean(values):.3f}"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    return lines + ["| " + " | ".join(row) + " |" for row in rows]


def summarize(flow: Path) -> str:
    state = json.loads((flow / "_state.json").read_text(encoding="utf-8"))
    if not state.get("metrics"):
        raise SystemExit(f"{flow / '_state.json'} declares no metrics; copy them from evals/runs/_state.json")
    metrics, prices = state["metrics"], state.get("prices", {})
    names = variants(flow)
    rows = {v: _read_jsonl(flow / v / "results.jsonl") for v in names}
    errors = {v: _read_jsonl(flow / v / "errors.jsonl") for v in names}
    means = {
        v: {m["id"]: case_means(rows[v], lambda r, k=m["id"]: r["grade"].get(k)) for m in metrics}
        for v in names
    }

    out = [
        f"# Eval summary: {state.get('flow', flow.name)}",
        "",
        "Generated by `python -m evals.summarize` from `results.jsonl`. Do not edit by hand.",
        "",
        "Each score is a mean over cases, with a 95% bootstrap interval in brackets and the "
        "number of cases it covers. Failed attempts are never counted as scores.",
        "",
        "## Quality",
        "",
    ]
    lower = [m["label"] for m in metrics if m.get("better") == "lower"]
    out += _table(
        ["Variant", "Cases scored", "Failed attempts"] + [m["label"] for m in metrics],
        [
            [v, str(len({r["prompt_id"] for r in rows[v]})), str(len(errors[v]))]
            + [_score(list(means[v][m["id"]].values())) for m in metrics]
            for v in names
        ],
    )
    if lower:
        out += ["", f"Lower is better for: {', '.join(lower)}. Higher is better for the rest."]

    for v in [n for n in names if n != "baseline" and "baseline" in names]:
        out += ["", f"## {v} compared with baseline", ""]
        change_path = flow / v / "change.md"
        change = change_path.read_text(encoding="utf-8").strip() if change_path.exists() else ""
        if change:
            out += [f"Change: {change.splitlines()[0]}", ""]
        table = []
        for m in metrics:
            base, new = means["baseline"][m["id"]], means[v][m["id"]]
            deltas = [new[c] - base[c] for c in sorted(new) if c in base]
            if not deltas:
                table.append([m["label"], "n/a", "0", "n/a"])
                continue
            ci = bootstrap_ci(deltas)
            interval = f"[{ci[0]:+.2f}, {ci[1]:+.2f}]" if ci else "n/a"
            verdict = "n/a" if not ci else "within noise" if ci[0] <= 0 <= ci[1] else "clear change"
            table.append([m["label"], f"{statistics.fmean(deltas):+.2f} {interval}", str(len(deltas)), verdict])
        out += _table(["Metric", "Mean change per case", "Cases in both", "Verdict"], table)
        out += [
            "",
            "The change is paired: each case is compared with itself. \"Within noise\" means the "
            "interval includes zero, so the data cannot tell the two variants apart.",
        ]

    out += ["", "## Cost and speed per case", ""]
    perf_rows = []
    for v in names:
        def per_case(value, v=v):
            return list(case_means(rows[v], value).values())

        latency = per_case(lambda r: r.get("latency_s"))
        app = [app_cost(r, prices) for r in rows[v]]
        judged = [judge_cost(r, prices) for r in rows[v]]
        spend = app + judged + [app_cost(e, prices) for e in errors[v]] + [judge_cost(e, prices) for e in errors[v]]
        perf_rows.append(
            [
                v,
                f"{statistics.median(latency):.0f} s" if latency else "n/a",
                _money(app),
                _money(judged),
                *(
                    f"{statistics.fmean(vals):.1f}" if vals else "n/a"
                    for vals in (
                        per_case(lambda r: r.get("rounds")),
                        per_case(lambda r: r.get("tool_calls")),
                        per_case(lambda r: r.get("sources_cited")),
                        per_case(lambda r: r.get("report_words")),
                    )
                ),
                "not measured" if not spend or None in spend else f"${sum(spend):.2f}",
            ]
        )
    out += _table(
        ["Variant", "Median latency", "App cost", "Judge cost", "Rounds", "Tool calls",
         "Sources cited", "Report words", "Total spent"],
        perf_rows,
    )
    out += [
        "",
        "Costs are means per scored attempt, derived from the token counts and model in each "
        "row and the prices in `_state.json`. Web search fees are not included. Total spent "
        "also counts failed attempts. Latency covers the research run only, not grading.",
    ]

    out += ["", "## By group", ""]
    group_rows = []
    for v in names:
        groups = dict.fromkeys(r["tags"][0] for r in rows[v])
        for group in groups:
            subset = [r for r in rows[v] if r["tags"][0] == group]
            group_rows.append(
                [v, group, str(len({r["prompt_id"] for r in subset}))]
                + [
                    _score(list(case_means(subset, lambda r, k=k: r["grade"].get(k)).values()))
                    for k in ("groundedness", "completeness", "trap_handled")
                ]
            )
    out += _table(["Variant", "Group", "Cases", "Groundedness", "Completeness", "Trap handled"], group_rows)

    if any(errors.values()):
        out += ["", "## Failed attempts", ""]
        failure_rows = []
        for v in names:
            classes: dict[str, int] = {}
            for e in errors[v]:
                classes[e.get("failure_class", "error")] = classes.get(e.get("failure_class", "error"), 0) + 1
            failure_rows += [[v, name, str(count)] for name, count in sorted(classes.items())]
        out += _table(["Variant", "Failure class", "Attempts"], failure_rows)
        out += ["", "A failed attempt is retried the next time the same command is run."]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Summarise benchmark results.")
    parser.add_argument("--flow", type=Path, default=DEFAULT_FLOW)
    args = parser.parse_args(argv)
    if not any(_read_jsonl(args.flow / v / "results.jsonl") for v in variants(args.flow)):
        raise SystemExit(f"No results under {args.flow}. Run `python -m evals.run` first.")
    text = summarize(args.flow)
    (args.flow / "summary.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
